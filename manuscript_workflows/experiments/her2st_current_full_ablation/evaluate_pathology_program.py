#!/usr/bin/env python3
"""Evaluate recovery of a train-defined tumor program on held-out HER2ST patients."""

from __future__ import annotations
from workflow_paths import DATA_ROOT

import argparse
import json
import sys
import types
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from scipy.stats import rankdata


ROOT = DATA_ROOT
for path in (ROOT, ROOT / "scripts"):
    if str(path) not in sys.path:
        sys.path.append(str(path))

from experiments.sample_split_fullgenes_v4_structured_loss.eval_sample_split_v4 import (  # noqa: E402
    forward_model,
    load_config,
)
from gnn_dataloader import SpatioS2EDataset  # noqa: E402
from models.stage0_reg_model_factory import build_stage0_reg_model  # noqa: E402


EXP = ROOT / "experiments/her2st_current_full_ablation"
TEST_SAMPLES = ("G2", "H1")
TUMOR_LABELS = {"invasive cancer", "cancer in situ"}
NONTUMOR_LABELS = {
    "adipose tissue",
    "breast glands",
    "connective tissue",
    "immune infiltrate",
}


def resolve(path: str | Path) -> Path:
    candidate = Path(path)
    return candidate if candidate.is_absolute() else ROOT / candidate


def binary_auc(labels: np.ndarray, scores: np.ndarray) -> float:
    labels = labels.astype(bool)
    n_positive = int(labels.sum())
    n_negative = int((~labels).sum())
    if n_positive == 0 or n_negative == 0:
        return float("nan")
    ranks = rankdata(scores, method="average")
    u_statistic = ranks[labels].sum() - n_positive * (n_positive + 1) / 2.0
    return float(u_statistic / (n_positive * n_negative))


def correlation(left: np.ndarray, right: np.ndarray) -> float:
    if np.std(left) <= 1.0e-8 or np.std(right) <= 1.0e-8:
        return float("nan")
    return float(np.corrcoef(left, right)[0, 1])


def install_embedding_cache(model: torch.nn.Module, path: Path) -> None:
    """Replace Decima sequence encoding with embeddings produced by that encoder."""
    cache = np.load(path, allow_pickle=False)
    cached_gene_ids = cache["gene_ids"].astype(str).tolist()
    embeddings = cache["embeddings"].astype(np.float32, copy=False)
    gene_to_index = {gene_id: index for index, gene_id in enumerate(cached_gene_ids)}
    tensor_cache: dict[tuple[str, ...], torch.Tensor] = {}

    def encode_genes(self, gene_ids, device):
        key = tuple(str(gene_id) for gene_id in gene_ids)
        if key not in tensor_cache:
            missing = [gene_id for gene_id in key if gene_id not in gene_to_index]
            if missing:
                raise KeyError(f"Embedding cache is missing {len(missing)} genes, including {missing[:5]}")
            indices = np.asarray([gene_to_index[gene_id] for gene_id in key], dtype=np.int64)
            # This environment combines an older PyTorch build with a newer NumPy
            # ABI, for which torch.from_numpy can reject an otherwise ordinary
            # ndarray. The program panel is small, so a list-backed construction
            # keeps the cached path portable without material overhead.
            tensor_cache[key] = torch.tensor(
                np.asarray(embeddings[indices], dtype=np.float32).tolist(),
                dtype=torch.float32,
            )
        return tensor_cache[key].to(device=device)

    model.decima.encode_genes = types.MethodType(encode_genes, model.decima)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--ckpt", type=Path, required=True)
    parser.add_argument("--variant", required=True)
    parser.add_argument("--save-dir", type=Path, required=True)
    parser.add_argument(
        "--embedding-cache",
        type=Path,
        help="Optional cache generated by the frozen Decima encoder; avoids recomputing sequence features.",
    )
    args = parser.parse_args()

    cfg = load_config(args.config)
    program = np.load(EXP / "artifacts/pathology_program/tumor_program.npz")
    program_genes = program["gene_ids"].astype(str).tolist()
    program_lookup = {
        gene_id: (float(direction), float(mean), float(std))
        for gene_id, direction, mean, std in zip(
            program_genes,
            program["direction"],
            program["train_mean"],
            program["train_std"],
        )
    }
    dataset = SpatioS2EDataset(
        split="test",
        samples=TEST_SAMPLES,
        expression_root=resolve(cfg["paths"]["expression_root"]),
        multimodal_root=resolve(cfg["paths"]["multimodal_root"]),
        graph_root=resolve(cfg["paths"]["graph_root"]),
        targets_dense=True,
        normalize_modalities=bool(cfg.get("normalize_modalities", True)),
        modality_stats_path=resolve(cfg["paths"]["modality_stats"]),
        gene_filter=set(program_genes),
    )
    first = dataset[0]
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = build_stage0_reg_model(cfg, input_dim=int(first["x"].shape[1])).to(device)
    state = torch.load(args.ckpt, map_location=device)
    model.load_state_dict(state["model"])
    model.eval()
    if args.embedding_cache is not None:
        install_embedding_cache(model, resolve(args.embedding_cache))
    no_graph = bool(state.get("no_graph", False) or cfg.get("model", {}).get("no_graph", False))

    metric_rows = []
    spot_rows = []
    pooled_labels = []
    pooled_observed = []
    pooled_predicted = []
    with torch.no_grad():
        for item in dataset:
            sample = str(item["sample"])
            gene_ids = list(item["gene_ids"])
            direction = np.asarray([program_lookup[gene_id][0] for gene_id in gene_ids])
            train_mean = np.asarray([program_lookup[gene_id][1] for gene_id in gene_ids])
            train_std = np.asarray([program_lookup[gene_id][2] for gene_id in gene_ids])
            edge_weight = item["edge_weight"].to(device)
            if no_graph:
                edge_weight = torch.zeros_like(edge_weight)
            output = forward_model(
                model,
                item["x"].to(device),
                item["edge_index"].to(device),
                edge_weight,
                gene_ids,
                sample_name=sample,
            )
            # This environment combines an older PyTorch build with NumPy 2.x;
            # materialize plain arrays to avoid incompatible tensor-backed ndarrays.
            predicted = np.asarray(
                output["log_mu"].detach().cpu().float().tolist(), dtype=np.float32
            )
            observed = np.asarray(item["y"].cpu().float().tolist(), dtype=np.float32)
            observed_score = np.mean(
                ((observed - train_mean) / np.maximum(train_std, 1.0e-3)) * direction,
                axis=1,
            )
            predicted_score = np.mean(
                ((predicted - train_mean) / np.maximum(train_std, 1.0e-3)) * direction,
                axis=1,
            )

            annotations = pd.read_csv(EXP / "data/annotations" / f"{sample}.tsv", sep="\t")
            label_map = dict(
                zip(annotations["spot_id"].astype(str), annotations["pathology_label"].astype(str))
            )
            pathology = np.asarray([label_map.get(str(barcode), "") for barcode in item["barcodes"]])
            keep = np.isin(pathology, sorted(TUMOR_LABELS | NONTUMOR_LABELS))
            binary = np.isin(pathology[keep], sorted(TUMOR_LABELS))
            obs_kept = observed_score[keep]
            pred_kept = predicted_score[keep]
            metric_rows.append(
                {
                    "variant": args.variant,
                    "sample": sample,
                    "n_labeled": int(keep.sum()),
                    "n_tumor": int(binary.sum()),
                    "n_nontumor": int((~binary).sum()),
                    "observed_program_auc": binary_auc(binary, obs_kept),
                    "predicted_program_auc": binary_auc(binary, pred_kept),
                    "predicted_vs_observed_program_pcc": correlation(pred_kept, obs_kept),
                    "observed_tumor_contrast": float(obs_kept[binary].mean() - obs_kept[~binary].mean()),
                    "predicted_tumor_contrast": float(pred_kept[binary].mean() - pred_kept[~binary].mean()),
                }
            )
            pooled_labels.append(binary)
            pooled_observed.append(obs_kept)
            pooled_predicted.append(pred_kept)
            for barcode, label, obs_score, pred_score in zip(
                np.asarray(item["barcodes"])[keep], pathology[keep], obs_kept, pred_kept
            ):
                spot_rows.append(
                    {
                        "variant": args.variant,
                        "sample": sample,
                        "spot_id": barcode,
                        "pathology_label": label,
                        "observed_program_score": float(obs_score),
                        "predicted_program_score": float(pred_score),
                    }
                )

    labels = np.concatenate(pooled_labels)
    observed = np.concatenate(pooled_observed)
    predicted = np.concatenate(pooled_predicted)
    metric_rows.append(
        {
            "variant": args.variant,
            "sample": "pooled_G2_H1",
            "n_labeled": int(len(labels)),
            "n_tumor": int(labels.sum()),
            "n_nontumor": int((~labels).sum()),
            "observed_program_auc": binary_auc(labels, observed),
            "predicted_program_auc": binary_auc(labels, predicted),
            "predicted_vs_observed_program_pcc": correlation(predicted, observed),
            "observed_tumor_contrast": float(observed[labels].mean() - observed[~labels].mean()),
            "predicted_tumor_contrast": float(predicted[labels].mean() - predicted[~labels].mean()),
        }
    )
    args.save_dir.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(metric_rows).to_csv(args.save_dir / "pathology_program_metrics.csv", index=False)
    pd.DataFrame(spot_rows).to_csv(
        args.save_dir / "pathology_program_spot_scores.tsv", sep="\t", index=False
    )
    summary = metric_rows[-1]
    (args.save_dir / "pathology_program_summary.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
